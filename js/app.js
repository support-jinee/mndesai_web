function renderFuelRates() {
    if (!siteData || !Array.isArray(siteData.fuels)) return;

    const isEditMode = document.body.classList.contains("wysiwyg-edit-mode-active");

    const quickRatesContainer = document.getElementById("quick-rates-container");
    if (quickRatesContainer) {
        quickRatesContainer.innerHTML = "";

        const activeFuels = siteData.fuels.filter(f => !f.hidden);
        activeFuels.slice(0, 4).forEach(fuel => {
            const quickRow = document.createElement("div");
            quickRow.className = `quick-fuel-item ${fuel.id}`;

            const subtext = fuel.id === "petrol" ? "Unleaded" :
                fuel.id === "diesel" ? "High Speed Diesel" :
                    fuel.id === "cng" ? "Eco Natural Gas" : "Premium Performance";

            quickRow.innerHTML = `
                <div class="fuel-meta">
                    <span class="name">${fuel.name}</span>
                    <span class="type">${subtext}</span>
                </div>
                <div class="fuel-rate">
                    <span class="price">₹${Number(fuel.price).toFixed(2)}</span>
                    <span class="unit">/ ${fuel.unit}</span>
                </div>
            `;
            quickRatesContainer.appendChild(quickRow);
        });
    }

    const pricesGrid = document.getElementById("prices-grid-container");
    if (pricesGrid) {
        pricesGrid.innerHTML = "";

        siteData.fuels.forEach(fuel => {

            if (!isEditMode && fuel.hidden === true) {
                return;
            }

            const card = document.createElement("div");
            card.className = `glass-panel price-card ${fuel.id}`;
            if (isEditMode && fuel.hidden === true) {
                card.className += " item-card-hidden";
            }

            const iconClass = fuel.id === "cng" ? "fa-compress-arrows-alt" :
                fuel.id === "speed" ? "fa-fire-flame-curved" :
                    fuel.icon || "fa-gas-pump";

            let trendHtml = "";
            if (fuel.trend === "up") {
                trendHtml = `<span class="trend-badge up"><i class="fa-solid fa-caret-up"></i> +₹${Math.abs(fuel.change).toFixed(2)}</span>`;
            } else if (fuel.trend === "down") {
                trendHtml = `<span class="trend-badge down"><i class="fa-solid fa-caret-down"></i> -₹${Math.abs(fuel.change).toFixed(2)}</span>`;
            } else {
                trendHtml = `<span class="trend-badge stable"><i class="fa-solid fa-minus"></i> Stable</span>`;
            }

            let controlsHtml = "";
            if (isEditMode) {
                controlsHtml = `
                    <div class="item-edit-controls">
                        <button class="item-btn hide-btn" onclick="toggleHideFuelCard(event, '${fuel.id}')" title="Toggle Hide/Show Fuel"><i class="fa-solid ${fuel.hidden ? 'fa-eye-slash' : 'fa-eye'}"></i></button>
                        <button class="item-btn delete-btn" onclick="deleteFuelCard(event, '${fuel.id}')" title="Delete Fuel Price Card"><i class="fa-solid fa-trash"></i></button>
                    </div>
                `;
            }

            card.innerHTML = `
                ${controlsHtml}
                <div class="card-icon-wrap">
                    <i class="fa-solid ${iconClass}" data-fuel-icon-id="${fuel.id}"></i>
                </div>
                <h3 class="fuel-name-editable" data-fuel-id="${fuel.id}">${fuel.name}</h3>
                <span class="unit-label-editable" data-fuel-id="${fuel.id}">Active rate per ${fuel.unit}</span>
                <div class="display-price">
                    <span class="price-val-editable" data-fuel-id="${fuel.id}">${Number(fuel.price).toFixed(2)}</span><span class="price-unit">/${fuel.unit}</span>
                </div>
                <div class="price-card-footer">
                    <span>Change Today</span>
                    ${trendHtml}
                </div>
            `;

            if (isEditMode) {
                const editableName = card.querySelector(".fuel-name-editable");
                const editableUnitLabel = card.querySelector(".unit-label-editable");
                const editableVal = card.querySelector(".price-val-editable");
                const trendBadge = card.querySelector(".trend-badge");
                const editableIcon = card.querySelector(".card-icon-wrap i");

                if (editableIcon) {
                    editableIcon.style.cursor = "pointer";
                    editableIcon.title = "Click to Change Icon";
                    editableIcon.addEventListener("click", () => {
                        window.openIconPickerModal(editableIcon);
                    });
                }

                if (editableName) {
                    editableName.setAttribute("contenteditable", "true");
                    editableName.className += " wysiwyg-editable-element";
                    editableName.addEventListener("keydown", (e) => {
                        if (e.key === "Enter") e.preventDefault();
                    });
                }
                if (editableUnitLabel) {
                    editableUnitLabel.setAttribute("contenteditable", "true");
                    editableUnitLabel.className += " wysiwyg-editable-element";
                    editableUnitLabel.addEventListener("keydown", (e) => {
                        if (e.key === "Enter") e.preventDefault();
                    });
                }
                if (editableVal) {
                    editableVal.setAttribute("contenteditable", "true");
                    editableVal.className += " wysiwyg-editable-element";
                    editableVal.addEventListener("keydown", (e) => {
                        if (e.key === "Enter") e.preventDefault();
                    });

                    editableVal.addEventListener("keypress", (e) => {
                        if (!/[\d\.]/.test(e.key) && e.key !== "Enter") {
                            e.preventDefault();
                        }
                    });
                }

                if (trendBadge) {
                    trendBadge.title = "Click to cycle price trend status";
                    trendBadge.addEventListener("click", (e) => {
                        e.preventDefault();
                        e.stopPropagation();

                        const trends = ["stable", "up", "down"];
                        let nextIdx = (trends.indexOf(fuel.trend) + 1) % trends.length;
                        fuel.trend = trends[nextIdx];

                        if (fuel.trend === "up") fuel.change = 0.25;
                        else if (fuel.trend === "down") fuel.change = -0.20;
                        else fuel.change = 0.00;

                        renderFuelRates();
                        showWysiwygToast("Trend direction updated! Click 'Save Draft' at the bottom to finalize.", "success");
                    });
                }
            }

            pricesGrid.appendChild(card);
        });

        if (isEditMode) {
            const addPlaceholder = document.createElement("div");
            addPlaceholder.className = "glass-panel add-new-card-placeholder";
            addPlaceholder.innerHTML = `
                <i class="fa-solid fa-circle-plus"></i>
                <span>Add New Fuel</span>
            `;
            addPlaceholder.addEventListener("click", () => {
                addNewFuelCard();
            });
            pricesGrid.appendChild(addPlaceholder);
        }
    }
}

