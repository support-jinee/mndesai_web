async function setupLocalFileLink() {
    if (!('showOpenFilePicker' in window)) {
        showWysiwygToast("⚠ Browser not supported. Please use Chrome or Edge.", "error");
        return;
    }

    try {
        if (localDataFileHandle) {
            const perm = await localDataFileHandle.requestPermission({ mode: 'readwrite' });
            if (perm === 'granted') {
                const saved = await saveToLinkedFile();
                if (saved) {
                    showWysiwygToast("✓ Saved directly to data.json! Refresh the public view.", "success");
                } else {
                    showWysiwygToast("✓ data.json linked successfully! Click Save Draft again.", "success");
                }
                await updateFileSyncStatusUI();
                return;
            }
        }

        if (confirm("📂 Do you want to link your local 'data.json' file?\n\nConfirm / Yes → file picker will open → select 'data.json' inside the project folder.\n\nCancel / No → draft will be saved in browser storage only (you can manually Export data.json later).")) {
            const [handle] = await window.showOpenFilePicker({
                id: 'mndesai-data-json',
                startIn: 'documents',
                types: [{
                    description: 'MNDesai Database File',
                    accept: {
                        'application/json': ['.json']
                    }
                }],
                excludeAcceptAllOption: true
            });

            if (handle) {
                if (handle.name !== "data.json") {
                    alert("❌ Invalid file selected!\n\nPlease select the file named 'data.json'.");
                    return;
                }

                const perm = await handle.requestPermission({ mode: 'readwrite' });
                if (perm === 'granted') {
                    localDataFileHandle = handle;
                    await saveFileHandleToDB(handle);
                    const saved = await saveToLinkedFile();
                    if (saved) {
                        showWysiwygToast("✓ data.json linked and saved! Refresh the public view to see changes.", "success");
                    } else {
                        showWysiwygToast("✓ data.json linked! Please click 'Save Draft' one more time.", "success");
                    }
                } else {
                    showWysiwygToast("❌ Permission denied. Please try again.", "error");
                }
            }
        } else {
            showWysiwygToast("✓ Draft saved in browser! (To save directly to disk, click the 'Link local data.json' button below)", "success");
        }
    } catch (err) {
        if (err.name === 'AbortError') {
            console.log("M.N. Desai: User cancelled file picker.");
            showWysiwygToast("✓ Draft saved in browser (Linking cancelled).", "success");
        } else {
            console.warn("setupLocalFileLink error:", err);
            if (window.location.protocol === "file:") {
                alert("⚠ Browser Security:\n\nDirect file saving is not supported over the file:// protocol.\n\nPlease serve the site using one of the following methods:\n1. VS Code → 'Go Live' button (http://localhost:5500)\n2. Python: Run 'python -m http.server 8000' in cmd and open http://localhost:8000\n\nAfter opening via HTTP, click the 'Link local data.json' button to enable direct auto-saving!");
            } else {
                showWysiwygToast("Linking cancelled or an error occurred.", "error");
            }
        }
    }
    await updateFileSyncStatusUI();
}

async function saveToLinkedFile() {
    if (!localDataFileHandle) return false;
    try {
        const perm = await localDataFileHandle.queryPermission({ mode: 'readwrite' });
        if (perm !== 'granted') {
            return false;
        }
        
        const writable = await localDataFileHandle.createWritable();
        await writable.write(JSON.stringify(prepareDataForSave(siteData), null, 2));
        await writable.close();
        return true;
    } catch (e) {
        console.error("Failed to write to linked file", e);
        return false;
    }
}


function processLoadedData(data) {
    if (!data) return data;
    
    // Make copies of lists if they exist so we don't mutate original objects unexpectedly
    if (data.fuels) data.fuels = JSON.parse(JSON.stringify(data.fuels));
    else data.fuels = [];
    
    if (data.services) data.services = JSON.parse(JSON.stringify(data.services));
    else data.services = [];
    
    if (data.testimonials) data.testimonials = JSON.parse(JSON.stringify(data.testimonials));
    else data.testimonials = [];

    if (data.legacyItems) data.legacyItems = JSON.parse(JSON.stringify(data.legacyItems));
    else data.legacyItems = JSON.parse(JSON.stringify(BASELINE_DEFAULT_DATA.legacyItems));
    
    // Merge hidden fuels
    if (Array.isArray(data.hiddenFuels)) {
        data.hiddenFuels.forEach(f => { f.hidden = true; });
        const fuelIds = new Set(data.fuels.map(f => f.id));
        data.hiddenFuels.forEach(f => {
            if (!fuelIds.has(f.id)) {
                data.fuels.push(f);
            }
        });
    }
    
    // Merge hidden services
    if (Array.isArray(data.hiddenServices)) {
        data.hiddenServices.forEach(s => { s.hidden = true; });
        const serviceIds = new Set(data.services.map(s => s.id));
        data.hiddenServices.forEach(s => {
            if (!serviceIds.has(s.id)) {
                data.services.push(s);
            }
        });
    }
    
    // Merge hidden testimonials
    if (Array.isArray(data.hiddenTestimonials)) {
        data.hiddenTestimonials.forEach(t => { t.hidden = true; });
        // Since testimonials don't have unique IDs, we just append them to the testimonials array
        data.testimonials = [...data.testimonials, ...data.hiddenTestimonials];
    }

    // Merge hidden legacy items
    if (Array.isArray(data.hiddenLegacyItems)) {
        data.hiddenLegacyItems.forEach(item => { item.hidden = true; });
        const legacyIds = new Set(data.legacyItems.map(item => item.id));
        data.hiddenLegacyItems.forEach(item => {
            if (!legacyIds.has(item.id)) {
                data.legacyItems.push(item);
            }
        });
    }
    
    // Merge baseline availableImages if missing from loaded data
    if (!data.availableImages) {
        data.availableImages = JSON.parse(JSON.stringify(BASELINE_DEFAULT_DATA.availableImages));
    } else {
        BASELINE_DEFAULT_DATA.availableImages.forEach(img => {
            if (!data.availableImages.includes(img)) {
                data.availableImages.push(img);
            }
        });
    }

    // Merge baseline availableVideos if missing from loaded data
    if (!data.availableVideos) {
        data.availableVideos = JSON.parse(JSON.stringify(BASELINE_DEFAULT_DATA.availableVideos));
    } else {
        BASELINE_DEFAULT_DATA.availableVideos.forEach(vid => {
            if (!data.availableVideos.includes(vid)) {
                data.availableVideos.push(vid);
            }
        });
    }

    // Merge baseline navbar items if missing from loaded data
    if (!data.navbar) {
        data.navbar = JSON.parse(JSON.stringify(BASELINE_DEFAULT_DATA.navbar));
    } else {
        const navIds = new Set(data.navbar.map(n => n.id));
        BASELINE_DEFAULT_DATA.navbar.forEach(item => {
            if (!navIds.has(item.id)) {
                data.navbar.push(JSON.parse(JSON.stringify(item)));
            }
        });
    }

    return data;
}

function prepareDataForSave(data) {
    if (!data) return data;
    const copy = JSON.parse(JSON.stringify(data));
    
    if (!copy.fuels) copy.fuels = [];
    if (!copy.services) copy.services = [];
    if (!copy.testimonials) copy.testimonials = [];
    if (!copy.legacyItems) copy.legacyItems = [];
    
    copy.hiddenFuels = copy.fuels.filter(f => f.hidden === true);
    copy.fuels = copy.fuels.filter(f => !f.hidden);
    
    // Strip the temporary 'hidden' property from hidden arrays to keep them clean
    copy.hiddenFuels.forEach(f => { delete f.hidden; });
    
    copy.hiddenServices = copy.services.filter(s => s.hidden === true);
    copy.services = copy.services.filter(s => !s.hidden);
    copy.hiddenServices.forEach(s => { delete s.hidden; });
    
    copy.hiddenTestimonials = copy.testimonials.filter(t => t.hidden === true);
    copy.testimonials = copy.testimonials.filter(t => !t.hidden);
    copy.hiddenTestimonials.forEach(t => { delete t.hidden; });

    copy.hiddenLegacyItems = copy.legacyItems.filter(item => item.hidden === true);
    copy.legacyItems = copy.legacyItems.filter(item => !item.hidden);
    copy.hiddenLegacyItems.forEach(item => { delete item.hidden; });
    
    return copy;
}

