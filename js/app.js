function setupWysiwygDragAndDrop() {
    const overlay = document.getElementById("wysiwyg-drag-overlay");
    if (!overlay) return;

    window.addEventListener("dragenter", (e) => {
        e.preventDefault();
        overlay.classList.add("dragover-active");
    });

    overlay.addEventListener("dragover", (e) => {
        e.preventDefault();
    });

    overlay.addEventListener("dragleave", (e) => {
        e.preventDefault();

        if (e.relatedTarget === null) {
            overlay.classList.remove("dragover-active");
        }
    });

    overlay.addEventListener("drop", (e) => {
        e.preventDefault();
        overlay.classList.remove("dragover-active");

        const files = e.dataTransfer.files;
        if (files.length > 0) {
            processUploadedWysiwygJSON(files[0]);
        }
    });
}

function processUploadedWysiwygJSON(file) {
    if (file.type !== "application/json" && !file.name.endsWith(".json")) {
        showWysiwygToast("Invalid file format. Only JSON is supported.", "error");
        return;
    }

    const reader = new FileReader();
    reader.onload = (e) => {
        try {
            const parsedData = JSON.parse(e.target.result);
            if (parsedData.stationName) {
                siteData = processLoadedData(parsedData);

                localStorage.setItem("mndesai_site_data", JSON.stringify(siteData));

                populateBrandingAndGeneral();
                renderFuelRates();
                setupTripCalculator();
                renderServices();
                populateQualityAssurance();
                renderTestimonials();
                populateContactAndFooter();

                showWysiwygToast("JSON configuration imported successfully!", "success");
            } else {
                showWysiwygToast("Invalid data.json schema. Missing key properties.", "error");
            }
        } catch (err) {
            showWysiwygToast("Failed to parse JSON file. Ensure syntax is valid.", "error");
        }
    };
    reader.readAsText(file);
}

function showWysiwygToast(message, type = "success") {
    const toast = document.getElementById("wysiwyg-toast-box");
    const textNode = document.getElementById("wysiwyg-toast-text");

    if (toast && textNode) {
        textNode.innerText = message;

        if (type === "error") {
            toast.className = "toast-msg error show";
            toast.querySelector("i").className = "fa-solid fa-circle-exclamation";
        } else {
            toast.className = "toast-msg success show";
            toast.querySelector("i").className = "fa-solid fa-circle-check";
        }

        setTimeout(() => {
            toast.classList.remove("show");
        }, 4000);
    }
}

