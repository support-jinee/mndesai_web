function setupNavigationEffects() {
    const header = document.getElementById("site-header");
    window.addEventListener("scroll", () => {
        if (window.scrollY > 50) {
            header.classList.add("scrolled");
            document.body.classList.add("scrolled-active");
        } else {
            header.classList.remove("scrolled");
            document.body.classList.remove("scrolled-active");
        }
        updateActiveNavLink();
    });

    const toggleBtn = document.getElementById("nav-menu-toggle");
    const siteNav = document.getElementById("site-nav");
    if (toggleBtn && siteNav) {
        toggleBtn.addEventListener("click", () => {
            siteNav.classList.toggle("open");
            const icon = toggleBtn.querySelector("i");
            if (siteNav.classList.contains("open")) {
                icon.className = "fa-solid fa-xmark";
            } else {
                icon.className = "fa-solid fa-bars";
            }
        });

        const navLinks = siteNav.querySelectorAll("ul li a");
        navLinks.forEach(link => {
            link.addEventListener("click", () => {
                siteNav.classList.remove("open");
                toggleBtn.querySelector("i").className = "fa-solid fa-bars";
            });
        });
    }
}

function updateActiveNavLink() {
    const sections = document.querySelectorAll("section");
    const navLinks = document.querySelectorAll("nav ul li a");

    let currentId = "hero";
    sections.forEach(sec => {
        const secTop = sec.offsetTop - 160;
        if (window.scrollY >= secTop) {
            currentId = sec.getAttribute("id");
        }
    });

    navLinks.forEach(link => {
        link.classList.remove("active");
        if (link.getAttribute("href") === `#${currentId}`) {
            link.classList.add("active");
        }
    });
}

